def seed():
    Base.metadata.create_all(engine)
    with SessionLocal() as db:
        for i, row in enumerate(ROWS):
            mid, title, year, runtime, genres, language, rating, poster, overview = row
            values = dict(
                tmdb_id=mid,
                title=title,
                original_title=title,
                release_date=date(year, 1, 1),
                runtime=runtime,
                genre_ids=genres,
                original_language=language,
                tmdb_rating=rating,
                popularity=100 - i,
                poster_path=poster,
                overview=overview,
                cast_names=[],
            )
            if mid == 157336:
                values.update(
                    backdrop_path="/xJHokMbljvjADYdit5fK5VQsXEG.jpg",
                    trailer_key="zSWdZVtXT7E",
                    cast_names=[
                        "Matthew McConaughey",
                        "Anne Hathaway",
                        "Jessica Chastain",
                    ],
                )
            db.execute(
                insert(Movie)
                .values(**values)
                .on_conflict_do_nothing(index_elements=[Movie.tmdb_id])
            )
        db.commit()
    print(f"Catalog ready: {len(ROWS)} sample movies (existing records preserved).")


if __name__ == "__main__":
    seed()
